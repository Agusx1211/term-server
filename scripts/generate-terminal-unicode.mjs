import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(projectRoot, "src/client/lib/terminal-unicode-ranges.ts");
const generatorDir = mkdtempSync(resolve(tmpdir(), "term-server-unicode-"));

const manifest = String.raw`[package]
name = "term-server-unicode-generator"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
unicode-width = { version = "=0.2.2", default-features = false }
`;

const source = String.raw`use unicode_width::{UnicodeWidthChar, UNICODE_VERSION};

const FNV_OFFSET: u64 = 0xcbf29ce484222325;
const FNV_PRIME: u64 = 0x100000001b3;

fn terminal_width(codepoint: u32) -> Option<u8> {
    char::from_u32(codepoint).map(|value| match value.width() {
        Some(width) => width.min(2) as u8,
        None if codepoint < 256 => 0,
        None => 1,
    })
}

fn flush(range: Option<(u8, u32, u32)>) {
    if let Some((width, start, end)) = range {
        println!("range {width} {start:X} {end:X}");
    }
}

fn main() {
    println!(
        "version {} {} {}",
        UNICODE_VERSION.0,
        UNICODE_VERSION.1,
        UNICODE_VERSION.2,
    );
    let mut hash = FNV_OFFSET;
    let mut counts = [0_u32; 3];
    let mut range = None;
    for codepoint in 0..=0x10ffff {
        let width = terminal_width(codepoint);
        let byte = width.unwrap_or(0xff);
        hash = (hash ^ u64::from(byte)).wrapping_mul(FNV_PRIME);
        if let Some(width) = width {
            counts[usize::from(width)] += 1;
        }
        match (range, width) {
            (Some((current, start, _)), Some(next)) if current == next && next != 1 => {
                range = Some((current, start, codepoint));
            }
            (current, Some(next)) if next != 1 => {
                flush(current);
                range = Some((next, codepoint, codepoint));
            }
            (current, _) => {
                flush(current);
                range = None;
            }
        }
    }
    flush(range);
    println!("counts {} {} {}", counts[0], counts[1], counts[2]);
    println!("fnv1a64 {hash:016x}");
}
`;

try {
  mkdirSync(resolve(generatorDir, "src"));
  writeFileSync(resolve(generatorDir, "Cargo.toml"), manifest);
  writeFileSync(resolve(generatorDir, "src/main.rs"), source);
  const generated = execFileSync(
    "cargo",
    ["run", "--quiet", "--manifest-path", resolve(generatorDir, "Cargo.toml")],
    { encoding: "utf8" },
  );
  const lines = generated.trim().split("\n");
  const version = lines.shift()?.split(" ").slice(1).join(".");
  const counts = lines.find((line) => line.startsWith("counts "))?.split(" ").slice(1).map(Number);
  const hash = lines.find((line) => line.startsWith("fnv1a64 "))?.split(" ")[1];
  const ranges = lines
    .filter((line) => line.startsWith("range "))
    .map((line) => {
      const [, width, start, end] = line.split(" ");
      return { width: Number(width), start: Number.parseInt(start, 16), end: Number.parseInt(end, 16) };
    });
  if (version !== "17.0.0" || counts?.length !== 3 || !hash) {
    throw new Error(`unexpected unicode-width generator output for Unicode ${version ?? "unknown"}`);
  }
  const renderRanges = (width) => ranges
    .filter((range) => range.width === width)
    .map(({ start, end }) => `  [${hex(start)}, ${hex(end)}],`)
    .join("\n");
  const output = `// Generated by \`npm run generate:terminal-unicode\`; do not edit manually.
// Source: unicode-width 0.2.2 / Unicode ${version}, using UnicodeWidthChar::width.
// panoptes-vt100 0.16.2 ignores Latin-1 controls and represents every width > 1
// with one continuation cell, so the browser table applies those same rules.

export const PANOPTES_UNICODE_VERSION = "17-panoptes";
export const PANOPTES_UNICODE_WIDTH_COUNTS = [${counts.join(", ")}] as const;
export const PANOPTES_UNICODE_WIDTH_FNV1A64 = "${hash}";

export const PANOPTES_ZERO_WIDTH_RANGES = [
${renderRanges(0)}
] as const;

export const PANOPTES_WIDE_RANGES = [
${renderRanges(2)}
] as const;
`;
  if (process.argv.includes("--check")) {
    if (readFileSync(outputPath, "utf8") !== output) {
      throw new Error("terminal Unicode ranges are stale; run npm run generate:terminal-unicode");
    }
    console.log(`Verified ${outputPath}`);
  } else {
    writeFileSync(outputPath, output);
    console.log(`Generated ${outputPath}`);
  }
} finally {
  rmSync(generatorDir, { recursive: true, force: true });
}

function hex(value) {
  return `0x${value.toString(16).toUpperCase().padStart(4, "0")}`;
}
